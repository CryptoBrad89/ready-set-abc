const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || '/usr/local/lib/pnpm/5/.pnpm/playwright-core@1.59.1/node_modules/playwright-core');

(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
  const results = [];
  const errors = [];
  const url = `file://${path.resolve(__dirname, '../index.html')}`;
  const context = await browser.newContext({ viewport: { width: 1180, height: 820 } });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  const route = async name => {
    await page.evaluate(name => { location.hash = name; }, name);
    await page.waitForFunction(name => document.body.dataset.current === name, name);
    await page.waitForTimeout(500);
  };
  const theme = async name => {
    await page.locator(`[data-theme-choice="${name}"]`).click();
    assert.equal(await page.locator('html').getAttribute('data-theme'), name);
    assert.equal(await page.locator(`[data-theme-choice="${name}"]`).getAttribute('aria-pressed'), 'true');
  };
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'pink');
  results.push('Fresh file load defaults to pink.');
  await theme('purple');
  await page.reload();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'purple');
  results.push('Theme persists across file reload.');
  await page.evaluate(() => localStorage.setItem('rsabc-r3-theme', '__proto__'));
  await page.reload();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'pink');
  results.push('Invalid stored theme falls back to pink.');
  await route('listen');
  await page.locator('[data-choice="apple"]').click();
  const feedback = await page.locator('#feedback').textContent();
  await theme('yellow');
  assert.equal(await page.locator('[data-choice="apple"]').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#feedback').textContent(), feedback);
  assert.equal(await page.locator('body').getAttribute('data-current'), 'listen');
  await page.locator('#check').click();
  assert.match(await page.locator('#feedback').textContent(), /Almost/);
  assert.equal(await page.locator('[data-choice="apple"]').getAttribute('aria-pressed'), 'false');
  await page.keyboard.press('1');
  await theme('purple');
  await page.locator('#check').click();
  await page.waitForFunction(() => document.body.dataset.current === 'celebrate');
  results.push('Picture selection and feedback survive theme changes. Wrong retry and keyboard-selected Sun success work.');
  await route('grownups');
  await page.keyboard.type('12');
  await theme('pink');
  assert.equal(await page.locator('.pin i').allTextContents().then(x => x.join('')), '●●○○');
  await page.keyboard.type('34');
  assert.equal(await page.locator('#round').isDisabled(), false);
  await page.locator('#round').click();
  const round = await page.locator('#round').textContent();
  await theme('yellow');
  assert.equal(await page.locator('#round').textContent(), round);
  results.push('Partial PIN survives switch. Keyboard PIN 1234 unlocks round size, retained across switch.');
  await page.locator('[data-audio="voice"]').click();
  await theme('purple');
  assert.equal(await page.locator('[data-audio="voice"]').getAttribute('aria-pressed'), 'false');
  await page.reload();
  assert.equal(await page.locator('[data-audio="voice"]').getAttribute('aria-pressed'), 'false');
  assert.equal(await page.locator('#round').textContent(), round);
  results.push('Voice preference and round size persist across reload.');
  await route('home');
  await page.evaluate(() => { location.hash = 'trail'; });
  await page.waitForTimeout(80);
  await page.keyboard.press('Escape');
  await page.waitForTimeout(700);
  assert.equal(await page.locator('body').getAttribute('data-current'), 'home');
  await page.evaluate(() => { location.hash = 'listen'; });
  await page.waitForTimeout(80);
  await page.evaluate(() => { location.hash = 'grownups'; });
  await page.waitForTimeout(700);
  assert.equal(await page.locator('body').getAttribute('data-current'), 'grownups');
  results.push('Escape cancels pending wipe and latest hash route wins.');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await route('celebrate');
  assert.equal(await page.locator('.tap-pop').count(), 0);
  assert.equal(await page.evaluate(() => document.getAnimations().filter(a => a.playState === 'running').length), 0);
  results.push('Reduced motion has no running CSS/Web animations or tap effects.');
  const blocked = await browser.newContext();
  await blocked.addInitScript(() => {
    Object.defineProperty(window, 'localStorage', { get() { throw new DOMException('Blocked', 'SecurityError'); } });
  });
  const blockedPage = await blocked.newPage();
  blockedPage.on('pageerror', error => errors.push(error.message));
  await blockedPage.goto(url);
  assert.equal(await blockedPage.locator('html').getAttribute('data-theme'), 'pink');
  await blockedPage.locator('[data-theme-choice="yellow"]').click();
  assert.equal(await blockedPage.locator('html').getAttribute('data-theme'), 'yellow');
  results.push('Blocked storage preserves initial render and live theme switching.');
  assert.deepEqual(errors, []);
  results.push('No uncaught page errors.');
  fs.writeFileSync(path.join(__dirname, 'runtime-report.json'), JSON.stringify({ passed: true, results, errors }, null, 2) + '\n');
  await browser.close();
  console.log(results.join('\n'));
})().catch(error => { console.error(error); process.exit(1); });
